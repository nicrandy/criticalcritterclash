// Build a SQL script that maps critter IDs to printed card numbers, from the
// CSVs produced by the QR-grid generator (set,card_number,index,row,col,id,url).
//
//   node scripts/make-card-number-sql.mjs <csv...> > scripts/setup_card_numbers.sql
//
// Safe to re-run for future sets: the output uses UPDATE-by-id, so existing
// rows are simply re-asserted.
import fs from 'node:fs';

const files = process.argv.slice(2);
if (files.length === 0) {
  console.error('usage: node scripts/make-card-number-sql.mjs <csv files...>');
  process.exit(1);
}

const pairs = [];
for (const file of files) {
  const lines = fs.readFileSync(file, 'utf8').trim().split(/\r?\n/);
  for (const line of lines.slice(1)) {          // skip header
    const cols = line.split(',');
    const cardNumber = Number(cols[1]);
    const id = cols[5]?.trim().toUpperCase();
    if (!id || !Number.isFinite(cardNumber)) continue;
    pairs.push([id, cardNumber]);
  }
}

const values = pairs.map(([id, n]) => `  ('${id}', ${n})`).join(',\n');
console.log(`-- Generated by scripts/make-card-number-sql.mjs — ${pairs.length} cards
-- Maps each critter to the card number printed below its QR code.
-- NOTE: card numbers are NOT unique (the original 16-card batch reuses
-- numbers 101-116 that set 1 also uses), so no unique constraint.

ALTER TABLE critters ADD COLUMN IF NOT EXISTS card_number INT;

UPDATE critters AS c
   SET card_number = v.card_number
  FROM (VALUES
${values}
  ) AS v(id, card_number)
 WHERE c.id = v.id;
`);
